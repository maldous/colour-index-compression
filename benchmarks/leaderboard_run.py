#!/usr/bin/env python3
"""Resumable, local, complete-member benchmark with preserved physical streams."""
from __future__ import annotations

import argparse
import concurrent.futures
from dataclasses import asdict
import hashlib
import json
import os
from pathlib import Path
import pickle
import resource
import subprocess
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from benchmarks.local_compare import source_digest


def atomic_json(path, value):
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(value, indent=2) + '\n')
    temp.replace(path)


def worker(args):
    acceleration = None
    if args.fast_comb:
        from benchmarks.fast_runtime import enable
        acceleration = enable(memoize=args.memoize)
    if args.ppm_key_cache:
        from benchmarks.ppm_key_cache import enable
        enable()
        acceleration = dict(acceleration or {}, ppm_key_cache=True)
    if args.native_ppm:
        from benchmarks.native_ppm import enable
        enable(args.native_ppm)
        native_source = Path(__file__).with_name('native_ppm.cpp')
        acceleration = dict(acceleration or {}, native_ppm=True,
            native_source_sha256=hashlib.sha256(native_source.read_bytes()).hexdigest(),
            native_binary_sha256=hashlib.sha256(Path(args.native_ppm).read_bytes()).hexdigest())
    from cix.cli import config_for_level
    from cix.multinomial import StreamEncoder, StreamDecoder
    from cix.fileformat import _footer, split_file_wrapper
    item = json.loads(args.item)
    path = Path(item['path'])
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    name = item.get('corpus', 'silesia') + '-' + path.name
    result_path = out / (name + '.json')
    progress = out / (name + '.progress.json')
    state_path = out / (name + '.state')
    blob_path = out / (name + '.cixm')
    source_hash = source_digest(Path(__file__).resolve().parents[1])
    config = config_for_level(args.level)
    identity = dict(source_tree_sha256=source_hash, input_sha256=item['sha256'],
                    level=args.level, config=asdict(config), original=item['size'])
    # JSON-normalize tuples in the dataclass for stable comparison after reload.
    identity = json.loads(json.dumps(identity))
    if result_path.exists():
        old = json.loads(result_path.read_text())
        if old.get('identity') == identity and old.get('round_trip'):
            if (not blob_path.exists() or blob_path.stat().st_size != old['size']
                    or hashlib.sha256(blob_path.read_bytes()).hexdigest() != old['compressed_sha256']):
                raise RuntimeError('cached physical artifact is missing or has changed')
            print(json.dumps(old), flush=True)
            return
        raise RuntimeError('result identity mismatch; use a different output directory')
    data = path.read_bytes()
    if len(data) != item['size'] or hashlib.sha256(data).hexdigest() != item['sha256']:
        raise RuntimeError('input manifest mismatch')
    del data
    encoder = StreamEncoder(config)
    offset = size = 0
    elapsed = 0.0
    runtime_history = [sys.version]
    acceleration_history = [acceleration]
    if state_path.exists():
        # Only load checkpoints generated by this local run, never external pickle data.
        with state_path.open('rb') as f:
            state = pickle.load(f)
        if state['identity'] != identity:
            raise RuntimeError('checkpoint identity mismatch')
        encoder, offset, size, elapsed = (state[k] for k in ('encoder','offset','size','elapsed'))
        runtime_history = state.get('runtime_history', ['prior runtime not recorded'])
        if runtime_history[-1] != sys.version:
            runtime_history.append(sys.version)
        acceleration_history = state.get('acceleration_history',
            [{'legacy_checkpoint': 'prior acceleration not recorded in checkpoint'}])
        if acceleration_history[-1] != acceleration:
            acceleration_history.append(acceleration)
    started = time.perf_counter()
    with path.open('rb') as inp, blob_path.open('r+b' if blob_path.exists() else 'w+b') as dst:
        inp.seek(offset); dst.truncate(size); dst.seek(size)
        while chunk := inp.read(65536):
            dst.write(encoder.feed(chunk)); dst.flush()
            offset += len(chunk); size = dst.tell()
            duration = elapsed + time.perf_counter() - started
            state = dict(identity=identity, encoder=encoder, offset=offset, size=size,
                         elapsed=duration, runtime_history=runtime_history,
                         acceleration_history=acceleration_history)
            temp = state_path.with_suffix('.state.tmp')
            with temp.open('wb') as f:
                pickle.dump(state, f, protocol=pickle.HIGHEST_PROTOCOL)
            temp.replace(state_path)
            atomic_json(progress, dict(input_read=offset, processed=offset-len(encoder._buffer),
                                       original=item['size'], compressed_so_far=size,
                                       seconds=duration, pid=os.getpid()))
        dst.write(encoder.finish()); dst.flush(); size = dst.tell()
    encode_seconds = elapsed + time.perf_counter() - started
    started = time.perf_counter()
    decoder = StreamDecoder()
    restored_size = 0
    with blob_path.open('rb') as src, path.open('rb') as original:
        while packet := src.read(65536):
            restored = decoder.feed(packet)
            if restored != original.read(len(restored)):
                raise RuntimeError('round-trip byte mismatch')
            restored_size += len(restored)
        decoder.finish()
        if original.read(1) or restored_size != item['size']:
            raise RuntimeError('round-trip length mismatch')
    payload = blob_path.read_bytes()
    wrapper = payload + _footer(path.name)
    wrapped_payload, original_name = split_file_wrapper(wrapper)
    if wrapped_payload != payload or original_name != path.name:
        raise RuntimeError('file-wrapper verification failed')
    blob_path.with_suffix('.cix').write_bytes(wrapper)
    result = dict(identity=identity, corpus=item.get('corpus','silesia'), file=path.name,
                  original=item['size'], size=size, round_trip=True,
                  cli_wrapper_size=len(wrapper), cli_wrapper_sha256=hashlib.sha256(wrapper).hexdigest(),
                  compressed_sha256=hashlib.sha256(payload).hexdigest(),
                  encode_seconds=encode_seconds, decode_seconds=time.perf_counter()-started,
                  peak_rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
                  runtime=sys.version, runtime_history=runtime_history, acceleration=acceleration,
                  acceleration_history=acceleration_history,
                  models=list(encoder.block_descriptions))
    if args.memoize:
        from benchmarks.fast_runtime import cache_stats
        result['cache_stats'] = cache_stats()
    atomic_json(result_path,result)
    state_path.unlink(missing_ok=True)
    progress.unlink(missing_ok=True)
    print(json.dumps(result), flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--worker', action='store_true')
    p.add_argument('--item')
    p.add_argument('--manifest', default='results/corpus-manifest.json')
    p.add_argument('--output', required=True)
    p.add_argument('--level', type=int, default=3)
    p.add_argument('--jobs', type=int, default=8)
    p.add_argument('--python', default=sys.executable)
    p.add_argument('--fast-comb', action='store_true')
    p.add_argument('--memoize', action='store_true')
    p.add_argument('--ppm-key-cache', action='store_true')
    p.add_argument('--native-ppm', help='Explicit path to qualified experimental shared library')
    args = p.parse_args()
    if args.worker:
        worker(args); return
    items = json.loads(Path(args.manifest).read_text())
    out = Path(args.output); out.mkdir(parents=True,exist_ok=True)

    def run(item):
        name = item.get('corpus','silesia') + '-' + Path(item['path']).name
        command=[args.python,str(Path(__file__).resolve()),'--worker','--item',json.dumps(item),
                 '--output',args.output,'--level',str(args.level)]
        if args.fast_comb:
            command.append('--fast-comb')
        if args.memoize:
            command.append('--memoize')
        if args.ppm_key_cache:
            command.append('--ppm-key-cache')
        if args.native_ppm:
            command.extend(['--native-ppm', args.native_ppm])
        with (out/(name+'.log')).open('a') as log:
            result=subprocess.run(command,stdout=log,stderr=subprocess.STDOUT,
                                  env={**os.environ,'OMP_NUM_THREADS':'1'})
        print(name, 'verified' if result.returncode == 0 else 'FAILED',flush=True)
        return result.returncode

    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        failures=sum(code!=0 for code in pool.map(run,items))
    if failures:
        raise SystemExit(f'{failures} members failed; see per-member logs')


if __name__ == '__main__':
    main()
