"""Generate pinned mathematical constants, without reading any corpus data."""
from decimal import Decimal, localcontext, ROUND_HALF_UP
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'benchmarks/native/CixLogTables.hpp'


def render():
    with localcontext() as context:
        context.prec=80;ln2=Decimal(2).ln();n=Decimal(4096)
        rounded=lambda v:int(v.to_integral_value(rounding=ROUND_HALF_UP))
        logs=[rounded((1+Decimal(i)/n).ln()/ln2*(1<<30)) for i in range(4097)]
        exps=[rounded((-Decimal(i)/n*ln2).exp()*(1<<48)) for i in range(4097)]
    out=['// Mathematical constants generated by generate_register_log_tables.py.',
         '// Decoder uses these pinned integers, not platform floating-point math.',
         '#pragma once','#include <cstdint>','namespace cix_log_math {']
    for name,kind,values in [('LOG2_MANTISSA','uint32_t',logs),('EXP2_NEGATIVE','uint64_t',exps)]:
        out.append(f'static constexpr {kind} {name}[] = {{')
        for i in range(0,len(values),8):out.append('  '+', '.join(str(v) for v in values[i:i+8])+',')
        out.append('};')
    out.append('}');return '\n'.join(out)+'\n'


if __name__=='__main__':
    if OUTPUT.exists():raise ValueError('preserve pinned lookup constants')
    OUTPUT.write_text(render());print(OUTPUT)
