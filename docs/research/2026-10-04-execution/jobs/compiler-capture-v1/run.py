"""Leased capture of real current compiler argv; never historical provenance."""
import hashlib, json, os, shutil, subprocess
from pathlib import Path
assert os.environ.get("CIX_RELEASE_LEASE") == "1"
ROOT = Path(__file__).resolve().parents[5]
WORK = ROOT / "benchmark-work/native-rc-check-v1"
OUT = WORK / "compiler-capture-v1"
OUT.mkdir(exist_ok=False)
ROWS = []

def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def source_manifest():
    paths = [p for p in (ROOT / "rust/cix-native").rglob("*") if p.suffix in (".c", ".cc", ".cpp", ".h", ".hpp")]
    return {str(p.relative_to(ROOT)): sha(p) for p in sorted(paths)}
def header_manifest():
    roots = [WORK / "distribution-engineering-v4/stage/usr/include", ROOT / "rust/cix-native/adapters/squashfs/profile/include", ROOT / "rust/cix-native/adapters/squashfs/userspace/include"]
    return {str(p): sha(p) for root in roots if root.is_dir() for p in sorted(root.rglob("*.h"))}
def run(label, argv, cwd=OUT, env=None, required=True):
    p = subprocess.run([str(x) for x in argv], cwd=cwd, env={**os.environ, **(env or {})}, text=True, capture_output=True)
    ROWS.append({"label":label,"argv":[str(x) for x in argv],"cwd":str(cwd),"returncode":p.returncode,"stdout":p.stdout,"stderr":p.stderr,"required":required})
    (OUT / "receipt.json").write_text(json.dumps({"schema":"cix.compiler-capture.v1","kind":"NEW_ANALYSIS_CONFIGURATION","source_hashes":source_manifest(),"header_hashes":header_manifest(),"commands":ROWS},indent=2)+"\n")
    if required and p.returncode: raise RuntimeError(label + ": " + (p.stderr[-2000:] or p.stdout[-2000:]))

def cmake_project(label, project, targets, extra=()):
    build = OUT / label
    run(label+"-configure", ["cmake","-S",project,"-B",build,"-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",*extra])
    run(label+"-build", ["cmake","--build",build,"--parallel","4","--target",*targets])
    shutil.copy2(build / "compile_commands.json", OUT / (label+"-compile_commands.json"))

# Self-contained current projects: compiler databases are generated by CMake.
cmake_project("profile", ROOT/"rust/cix-native/adapters/squashfs/profile", ["cix_squashfs_profile","cix_squashfs_profile_contract"])
cmake_project("userspace", ROOT/"rust/cix-native/adapters/squashfs/userspace", ["cix_sqfs_userspace"])
sdk = WORK / "distribution-engineering-v4/stage/usr"
cmake_project("sdk-consumers", ROOT/"rust/cix-native/packaging/sdk/tests", ["cix_installed_cpp_consumer","cix_installed_stream_consumer","cix_installed_format_consumer","cix_installed_dictionary_consumer"], ["-DCMAKE_PREFIX_PATH="+str(sdk)])

# Direct documented helper with no host adapter dependency.
run("stream-source-generator", ["cc","-std=c11","-Wall","-Wextra","-Werror","-c",ROOT/"rust/cix-native/experiments/stream-qualification-v2/source-generator.c","-o",OUT/"source-generator.o"])

# These need a pinned host integration rather than invented standalone flags.
for path, host in {
 "rust/cix-native/adapters/squashfs/kernel/tests/xattr_check.c":"kernel-module target supplying Linux generated headers",
 "rust/cix-native/adapters/squashfs/tools/cix_compressor_table.c":"SquashFS tools pinned host target",
 "rust/cix-native/adapters/squashfs/tools/cix_wrapper.c":"SquashFS tools pinned host target",
 "rust/cix-native/adapters/squashfs/userspace/libsquashfs/cix_sqfsng_compressor.c":"libsquashfs-ng pinned host target",
 "rust/cix-native/adapters/squashfs/userspace/libsquashfs/cix_sqfsng_decode.c":"libsquashfs-ng pinned host target",
 "rust/cix-native/adapters/squashfs/userspace/libsquashfs/cix_sqfsng_read_super.c":"libsquashfs-ng pinned host target",
 "rust/cix-native/adapters/squashfs/userspace/tests/squashfuse_library_fixture_contract.c":"Squashfuse pinned host contract target",
 "rust/cix-native/adapters/squashfs/userspace/tests/squashfuse_xattr_contract.c":"Squashfuse pinned host contract target",
 "rust/cix-native/packaging/squash/squash-cix.c":"Squash codec host target"
}.items(): ROWS.append({"translation_unit":path,"status":"REQUIRES_PINNED_HOST_TARGET","host_target":host})
(OUT / "receipt.json").write_text(json.dumps({"schema":"cix.compiler-capture.v1","kind":"NEW_ANALYSIS_CONFIGURATION","source_hashes":source_manifest(),"header_hashes":header_manifest(),"commands":ROWS},indent=2)+"\n")
